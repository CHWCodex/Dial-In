// Writes the SQL that brings the database in line with the reviewed content (run after build-content.mjs).
//   node scripts/build-db-sync.mjs > supabase/migrations/<timestamp>_question_integrity_sync.sql
// It is idempotent: safe to apply more than once. Rows for dates up to UK today are never touched (the trigger enforces it too).
import { readFileSync } from 'node:fs';
import { loadGame } from './load-game.mjs';

const G = loadGame(), groups = JSON.parse(readFileSync(new URL('../content/question-groups.json', import.meta.url), 'utf8'));
const sched = JSON.parse(readFileSync(new URL('../content/schedule.json', import.meta.url), 'utf8'));
const q = s => `'${String(s).replace(/'/g, "''")}'`;
const from = sched.daily.from;
const out = [];
out.push(`-- Question integrity sync, generated by scripts/build-db-sync.mjs from content/ (reviewed schedule from ${from}).
-- 1. question metadata  2. guard on daily_sets  3. usage view  4. reviewed wording  5. reviewed schedule from ${from}
begin;

alter table public.questions
  add column if not exists fact_id text,
  add column if not exists status text not null default 'active',
  add column if not exists status_reason text,
  add column if not exists reviewed_on date;
do $$ begin
  alter table public.questions add constraint questions_status_check check (status in ('active', 'quarantined', 'retired'));
exception when duplicate_object then null; end $$;
create index if not exists questions_fact_id_idx on public.questions (fact_id);

-- Every daily puzzle row is checked as it is written. Published days (up to UK today) can't be edited or deleted, and a
-- new day can't reuse a fact that any other day already used, or a quarantined question. An advisory lock serialises
-- concurrent writers, so two jobs scheduling at once can't both slip the same question in.
-- Controlled correction of a published day (see docs/content/RUNBOOK.md): set local dialin.correction = 'on' in the same transaction.
create or replace function public.guard_daily_sets() returns trigger
language plpgsql security definer set search_path = public as $fn$
declare bad text; correcting boolean := coalesce(current_setting('dialin.correction', true), '') = 'on';
begin
  perform pg_advisory_xact_lock(hashtext('public.daily_sets'));
  if tg_op in ('UPDATE', 'DELETE') and old.puzzle_date <= public.uk_today() and not correcting then
    raise exception 'Published puzzle % cannot be changed (use the correction procedure)', old.puzzle_date;
  end if;
  if tg_op = 'DELETE' then return old; end if;
  if tg_op = 'INSERT' and new.puzzle_date < public.uk_today() and not correcting then
    raise exception 'Cannot add a puzzle for a past date (%)', new.puzzle_date;
  end if;
  if coalesce(array_length(new.question_ids, 1), 0) <> 7 or (select count(distinct x) from unnest(new.question_ids) x) <> 7 then
    raise exception 'A daily puzzle needs 7 different questions';
  end if;
  select string_agg(x, ', ') into bad from unnest(new.question_ids) x where not exists (select 1 from public.questions qq where qq.id = x and qq.status = 'active');
  if bad is not null then raise exception 'Not an active question: %', bad; end if;
  if (select count(distinct coalesce(qq.fact_id, qq.id)) from public.questions qq where qq.id = any(new.question_ids)) <> 7 then
    raise exception 'Two questions in this puzzle test the same fact';
  end if;
  if not correcting then
    select string_agg(distinct x, ', ') into bad
    from unnest(new.question_ids) x join public.questions qn on qn.id = x
    where exists (select 1 from public.daily_sets o cross join unnest(o.question_ids) y join public.questions qo on qo.id = y
                  where o.puzzle_date <> new.puzzle_date and coalesce(qo.fact_id, qo.id) = coalesce(qn.fact_id, qn.id));
    if bad is not null then raise exception 'Already used in another daily puzzle (same fact): %', bad; end if;
  end if;
  return new;
end $fn$;
revoke all on function public.guard_daily_sets() from public, anon, authenticated;
drop trigger if exists daily_sets_guard on public.daily_sets;

-- Where every question has been used (one row per question per puzzle). Not readable by players.
create or replace view public.question_usage with (security_invoker = true) as
  select qq.id as question_id, coalesce(qq.fact_id, qq.id) as fact_id, qq.category, qq.question, qq.answer, qq.unit, qq.source,
         qq.status, qq.reviewed_on, ds.puzzle_date, ds.puzzle_no, u.pos as position, ds.puzzle_date <= public.uk_today() as published
  from public.daily_sets ds cross join lateral unnest(ds.question_ids) with ordinality as u(qid, pos) join public.questions qq on qq.id = u.qid;
revoke all on public.question_usage from public, anon, authenticated;
`);
// 1. metadata
const facts = [];
for (const g of groups.factGroups) { const ids = g.filter(x => /^[a-z]+\d+$/.test(x)); ids.forEach(id => facts.push(`(${q(id)},${q(ids[0])})`)); }
out.push(`update public.questions set reviewed_on = date '2026-11-26' where reviewed_on is null;`);
out.push(`update public.questions qq set fact_id = v.f from (values ${facts.join(',')}) v(id, f) where qq.id = v.id and qq.fact_id is distinct from v.f;`);
for (const [id, why] of Object.entries(groups.quarantine)) out.push(`update public.questions set status = 'quarantined', status_reason = ${q(why)} where id = ${q(id)} and status <> 'quarantined';`);
// 4. reviewed wording (unpublished questions only; the text players see comes from the game, this keeps the database identical)
for (const id of Object.keys(groups.reworded)) { const x = G.BY_ID.get(id); out.push(`update public.questions set question = ${q(x.question)}, explanation = ${q(x.explanation)} where id = ${q(id)} and question is distinct from ${q(x.question)};`); }
// 5. schedule: drop the original schedule's unpublished rows from the start date, then add the reviewed ones
out.push(`delete from public.daily_sets where puzzle_date >= greatest(date ${q(from)}, public.uk_today() + 1);`);
const rows = sched.daily.days.map((ids, i) => { const d = G.DateUK.add(from, i); return `(${q(d)},${G.DateUK.puzzleNo(d)},array[${ids.map(q).join(',')}])`; });
out.push(`create trigger daily_sets_guard before insert or update or delete on public.daily_sets for each row execute function public.guard_daily_sets();`);
out.push(`insert into public.daily_sets (puzzle_date, puzzle_no, question_ids) select v.d::date, v.n, v.ids from (values\n${rows.join(',\n')}\n) v(d, n, ids) where v.d::date > public.uk_today() on conflict (puzzle_date) do nothing;`);
out.push(`commit;`);
console.log(out.join('\n'));
